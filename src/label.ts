import fs from "node:fs";
import path from "node:path";
import { IMAGES_PER_REQUEST, LABELS, LABELS_FILE, OPENROUTER_MODELS, type Label } from "./config.js";

export type LabelMap = Record<string, Label[]>;

/** Written in the Topics column when none of the labels apply. */
const NONE = "-";
const ROW_RE = /^\|\s*\d+\s*\|([^|]+)\|([^|]*)\|\s*$/;

/** Reads the labels table; rows with an empty Topics cell count as not labelled yet. */
export function loadLabels(file = LABELS_FILE): LabelMap {
  if (!fs.existsSync(file)) return {};
  const labels: LabelMap = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = ROW_RE.exec(line);
    const cell = m?.[2].trim();
    if (!m || !cell) continue;
    const names = cell === NONE ? [] : cell.split(";").map((s) => s.trim());
    const unknown = names.filter((n) => !(LABELS as readonly string[]).includes(n));
    if (unknown.length) throw new Error(`${file}: unknown topic(s) ${unknown.join(", ")} in row: ${line}`);
    labels[m[1].trim()] = names as Label[];
  }
  return labels;
}

/** Writes one table row per question (in `keys` order), followed by an index by topic. */
export function saveLabels(labels: LabelMap, keys: string[], file = LABELS_FILE) {
  const lines = [
    "# Paper 3 question topics",
    "",
    "Generated by `npm run build`, which also reads this file back, so edits here are kept.",
    `Separate topics with \`;\`. \`${NONE}\` means none of the topics apply; leave the cell empty to have it labelled again.`,
    "",
    "| # | Question | Topics |",
    "|---|---|---|",
    ...keys.map((k, i) => {
      const ls = labels[k];
      return `| ${i + 1} | ${k} | ${ls ? (ls.length ? ls.join("; ") : NONE) : ""} |`;
    }),
    "",
    "## By topic",
    "",
    ...LABELS.flatMap((label) => {
      const nums = keys.flatMap((k, i) => (labels[k]?.includes(label) ? [`Q${i + 1}`] : []));
      return [`### ${label} (${nums.length})`, "", nums.join(", ") || "None", ""];
    }),
  ];
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, lines.join("\n"));
}

// Topics are referred to by number in the reply to keep it short.
const PROMPT = `You are labelling Cambridge International A Level Mathematics 9709 Pure Mathematics 3 exam questions by topic.

The images show several questions. Each question starts with a bold line "ID <number>"; everything up to the next "ID" line belongs to that question.

Topics:
${LABELS.map((l, i) => `${i + 1}. ${l}`).join("\n")}

Give each question ALL topics that apply (a question covering several topics, including across its parts, gets several).
- "Algebra" covers polynomials, factor/remainder theorem, partial fractions, binomial expansion, modulus equations/inequalities.
- "Numerical Solutions/Iteration" covers locating roots, sign changes, iterative formulae and convergence.
- Label by the mathematics the question actually requires, not just words in the question.
- If no topic fits (e.g. a pure vectors question), give an empty list.

Reply with only a JSON object mapping each requested ID to its topic numbers, e.g. {"12": [2, 5], "13": []}.`;

export interface LabelJob {
  key: string;
  /** Number printed as "ID <n>" above the question in the images. */
  id: number;
  /** Indices into the image list of the pages this question appears on. */
  images: number[];
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Free models allow 20 requests a minute. */
const MIN_INTERVAL_MS = 4000;

/** Groups questions into requests of at most `IMAGES_PER_REQUEST` images, never splitting a question. */
export function planRequests(jobs: LabelJob[]) {
  const requests: { jobs: LabelJob[]; images: number[] }[] = [];
  for (const job of jobs) {
    const last = requests.at(-1);
    const merged = last ? [...new Set([...last.images, ...job.images])] : [];
    if (last && merged.length <= IMAGES_PER_REQUEST) {
      last.jobs.push(job);
      last.images = merged;
    } else requests.push({ jobs: [job], images: [...job.images] });
  }
  return requests;
}

class OpenRouterError extends Error {
  constructor(
    readonly status: number,
    message: string,
    readonly retryAfterMs: number,
  ) {
    super(message);
  }
}

interface ChatResponse {
  model?: string;
  choices?: { message?: { content?: string | null } }[];
  usage?: { prompt_tokens: number; completion_tokens: number };
  error?: { code?: number; message?: string; metadata?: unknown };
}

async function chat(apiKey: string, model: string, prompt: string, images: Buffer[]): Promise<ChatResponse> {
  const res = await fetch("https://openrouter.ai/api/v1/chat/completions", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json", "X-Title": "ASMathPDFParser" },
    body: JSON.stringify({
      model,
      messages: [
        {
          role: "user",
          content: [
            { type: "text", text: prompt },
            ...images.map((img) => ({ type: "image_url", image_url: { url: `data:image/jpeg;base64,${img.toString("base64")}` } })),
          ],
        },
      ],
      response_format: { type: "json_object" },
      reasoning: { effort: "low", exclude: true },
      temperature: 0,
      max_tokens: 4096,
    }),
  });
  const body = (await res.json().catch(() => ({}))) as ChatResponse;
  // errors can also arrive with a 200 status when the upstream provider fails
  const error = body.error ?? (res.ok ? undefined : { message: res.statusText });
  if (error) {
    const reset = Number(res.headers.get("x-ratelimit-reset"));
    const retryAfter = Number(res.headers.get("retry-after")) * 1000 || (reset > Date.now() ? reset - Date.now() : 0);
    const detail = error.metadata ? ` ${JSON.stringify(error.metadata)}` : "";
    throw new OpenRouterError(error.code ?? res.status, `${error.code ?? res.status}: ${error.message}${detail}`, retryAfter);
  }
  return body;
}

/** Pulls the JSON object out of a reply, tolerating code fences or stray text around it. */
export function parseReply(text: string): Record<string, unknown> {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  return start >= 0 && end > start ? JSON.parse(text.slice(start, end + 1)) : {};
}

/**
 * Labels the given questions with free OpenRouter vision models, sending page `images` (JPEG,
 * several questions each) up to `IMAGES_PER_REQUEST` at a time to stay within the free tier's
 * 50 requests a day. Results are saved after every request, so a run stopped by the daily limit
 * resumes where it left off. `allKeys` orders the rows of the labels file.
 */
export async function labelQuestions(jobs: LabelJob[], images: Buffer[], allKeys: string[]) {
  const apiKey = process.env.OPENROUTER_API_KEY;
  if (!apiKey) throw new Error("Set OPENROUTER_API_KEY (e.g. in .env) to label questions");
  const labels = loadLabels();

  let lastRequest = 0;
  // free models are often rate-limited by their upstream provider; on errors we move on to the
  // next model in the list, and stay on whichever one is working
  let modelIdx = 0;
  let pending = jobs.filter((j) => !labels[j.key]);
  for (let round = 1; pending.length && round <= 3; round++) {
    const requests = planRequests(pending);
    console.log(`  ${pending.length} questions in ${requests.length} request(s) via OpenRouter`);
    for (const [n, req] of requests.entries()) {
      const ids = req.jobs.map((j) => j.id);
      for (let tries = 1; ; tries++) {
        await sleep(Math.max(0, lastRequest + MIN_INTERVAL_MS - Date.now()));
        lastRequest = Date.now();
        console.log(`  [${n + 1}/${requests.length}] labelling IDs ${ids[0]}-${ids.at(-1)} (${ids.length} questions, ${req.images.length} images)`);
        try {
          const data = await chat(
            apiKey,
            OPENROUTER_MODELS[modelIdx],
            `${PROMPT}\n\nRequested IDs: ${ids.join(", ")}`,
            req.images.map((i) => images[i]),
          );
          const usage = data.usage ? `, ${data.usage.prompt_tokens} tokens in, ${data.usage.completion_tokens} out` : "";
          console.log(`    answered by ${data.model}${usage}`);
          const result = parseReply(data.choices?.[0]?.message?.content ?? "");
          let got = 0;
          for (const job of req.jobs) {
            const codes = result[String(job.id)];
            if (!Array.isArray(codes)) continue;
            labels[job.key] = LABELS.filter((_, i) => codes.map(Number).includes(i + 1));
            got++;
          }
          if (got < ids.length) console.warn(`    reply covered ${got}/${ids.length} questions`);
          saveLabels(labels, allKeys);
          break;
        } catch (err) {
          const status = err instanceof OpenRouterError ? err.status : 0;
          const message = err instanceof Error ? err.message : String(err);
          if (status === 401 || status === 402 || status === 403) throw err;
          if (status === 429 && /per.?day/i.test(message)) {
            throw new Error(`OpenRouter's daily free-model limit was reached; labels so far are saved in ${LABELS_FILE}. Rerun tomorrow to continue.\n${message}`);
          }
          // per-minute limits, overloaded upstream providers and network errors are worth retrying
          const retryable = status === 0 || status === 408 || status === 429 || status >= 500;
          const models = OPENROUTER_MODELS.length;
          if (retryable && tries < models * 3) {
            console.warn(`    ${OPENROUTER_MODELS[modelIdx]}: ${message.slice(0, 300)}`);
            modelIdx = (modelIdx + 1) % models;
            // back off only once every model has failed in a row
            const allFailed = tries % models === 0;
            const wait = allFailed ? (err instanceof OpenRouterError && err.retryAfterMs) || 30_000 * (tries / models) : 0;
            console.warn(`    retrying with ${OPENROUTER_MODELS[modelIdx]}${wait ? ` in ${Math.ceil(wait / 1000)}s` : ""}`);
            await sleep(wait);
            continue;
          }
          console.warn(`    request failed: ${message.slice(0, 500)}`);
          break;
        }
      }
    }
    pending = pending.filter((j) => !labels[j.key]);
    if (pending.length && round < 3) console.log(`  ${pending.length} questions still unlabelled, retrying them`);
  }
  if (pending.length) console.warn(`  gave up on ${pending.length} questions: ${pending.map((j) => j.id).join(", ")}`);
  return labels;
}
