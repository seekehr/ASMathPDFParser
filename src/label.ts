import fs from "node:fs";
import path from "node:path";
import { GoogleGenAI } from "@google/genai";
import { GEMINI_MIN_INTERVAL_S, GEMINI_MODEL, LABEL_BATCH_SIZE, LABELS, LABELS_FILE, type Label } from "./config.js";

export type LabelMap = Record<string, Label[]>;

/** Written in the Topics column when none of the labels apply. */
const NONE = "-";
const ROW_RE = /^\|\s*\d+\s*\|([^|]+)\|([^|]*)\|\s*$/;

/** Reads the labels table; rows with an empty Topics cell count as not labelled yet. */
export function loadLabels(): LabelMap {
  if (!fs.existsSync(LABELS_FILE)) return {};
  const labels: LabelMap = {};
  for (const line of fs.readFileSync(LABELS_FILE, "utf8").split(/\r?\n/)) {
    const m = ROW_RE.exec(line);
    const cell = m?.[2].trim();
    if (!m || !cell) continue;
    const names = cell === NONE ? [] : cell.split(";").map((s) => s.trim());
    const unknown = names.filter((n) => !(LABELS as readonly string[]).includes(n));
    if (unknown.length) throw new Error(`${LABELS_FILE}: unknown topic(s) ${unknown.join(", ")} in row: ${line}`);
    labels[m[1].trim()] = names as Label[];
  }
  return labels;
}

/** Writes one table row per question (in `keys` order), followed by an index by topic. */
export function saveLabels(labels: LabelMap, keys: string[]) {
  const lines = [
    "# Paper 3 question topics",
    "",
    "Generated by `npm run build`, which also reads this file back, so edits here are kept.",
    `Separate topics with \`;\`. \`${NONE}\` means none of the topics apply; leave the cell empty to have Gemini label it again.`,
    "",
    "| # | Question | Topics |",
    "|---|---|---|",
    ...keys.map((k, i) => {
      const ls = labels[k];
      return `| ${i + 1} | ${k} | ${ls ? (ls.length ? ls.join("; ") : NONE) : ""} |`;
    }),
    "",
    "## By topic",
    "",
    ...LABELS.flatMap((label) => {
      const nums = keys.flatMap((k, i) => (labels[k]?.includes(label) ? [`Q${i + 1}`] : []));
      return [`### ${label} (${nums.length})`, "", nums.join(", ") || "None", ""];
    }),
  ];
  fs.mkdirSync(path.dirname(LABELS_FILE), { recursive: true });
  fs.writeFileSync(LABELS_FILE, lines.join("\n"));
}

const PROMPT = `You are labelling Cambridge International A Level Mathematics 9709 Pure Mathematics 3 exam questions by topic.

The attached PDF contains many questions, several per page. Each question starts with a bold line "ID <number>"; everything up to the next "ID" line belongs to that question.

Give each question ALL of the following topic labels that apply (one or more; a question covering several topics, including across its parts, gets several labels):
${LABELS.map((l) => `- ${l}`).join("\n")}

Guidance:
- "Algebra" covers polynomials, factor/remainder theorem, partial fractions, binomial expansion, modulus equations/inequalities.
- "Numerical Solutions/Iteration" covers locating roots, sign changes, iterative formulae and convergence.
- Label by the mathematics the question actually requires, not just words in the question.
- If none of the labels fit (e.g. a pure vectors question), return an empty list for that question.

Return a JSON array with exactly one entry for every ID in the PDF.`;

const SCHEMA = {
  type: "array",
  items: {
    type: "object",
    properties: {
      id: { type: "integer" },
      labels: { type: "array", items: { type: "string", enum: [...LABELS] } },
    },
    required: ["id", "labels"],
  },
};

export interface LabelJob {
  key: string;
  /** Number printed as "ID <n>" above the question in the batch PDF. */
  id: number;
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Seconds Gemini asks us to wait after a 429, if it said. */
function retryDelaySeconds(message: string): number | null {
  const m = /"retryDelay":\s*"(\d+(?:\.\d+)?)s"/.exec(message);
  return m ? Number(m[1]) : null;
}

/**
 * Labels the given questions with Gemini. Questions are sent in large batches (`LABEL_BATCH_SIZE`)
 * with several questions packed per PDF page, and requests are spaced `GEMINI_MIN_INTERVAL_S`
 * apart, to stay inside free-tier request and token limits. `makePdf` renders one batch;
 * `allKeys` orders the rows of the labels file. Results are saved after every request, so a run
 * stopped by a daily quota resumes where it left off.
 */
export async function labelQuestions(
  jobs: LabelJob[],
  allKeys: string[],
  makePdf: (batch: LabelJob[]) => Promise<Uint8Array>,
) {
  const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;
  if (!apiKey) throw new Error("Set GEMINI_API_KEY (e.g. in .env) to label questions");
  const ai = new GoogleGenAI({ apiKey });
  const labels = loadLabels();

  let lastRequest = 0;
  let pending = jobs.filter((j) => !labels[j.key]);
  for (let round = 1; pending.length && round <= 3; round++) {
    const batches = Math.ceil(pending.length / LABEL_BATCH_SIZE);
    console.log(`  ${pending.length} questions in ${batches} request(s) of up to ${LABEL_BATCH_SIZE}`);
    for (let i = 0; i < pending.length; i += LABEL_BATCH_SIZE) {
      const batch = pending.slice(i, i + LABEL_BATCH_SIZE);
      const pdf = await makePdf(batch);
      for (let tries = 1; ; tries++) {
        const wait = lastRequest + GEMINI_MIN_INTERVAL_S * 1000 - Date.now();
        if (wait > 0) await sleep(wait);
        lastRequest = Date.now();
        console.log(`  labelling IDs ${batch[0].id}-${batch.at(-1)!.id} (${batch.length} questions) with ${GEMINI_MODEL}`);
        try {
          const res = await ai.models.generateContent({
            model: GEMINI_MODEL,
            contents: [
              {
                role: "user",
                parts: [{ inlineData: { mimeType: "application/pdf", data: Buffer.from(pdf).toString("base64") } }, { text: PROMPT }],
              },
            ],
            config: { responseMimeType: "application/json", responseJsonSchema: SCHEMA, temperature: 0 },
          });
          const usage = res.usageMetadata;
          if (usage) console.log(`    tokens: ${usage.promptTokenCount} in, ${usage.totalTokenCount} total`);
          const result = JSON.parse(res.text ?? "[]") as { id: number; labels: string[] }[];
          for (const { id, labels: ls } of result) {
            const job = batch.find((j) => j.id === id);
            if (job) labels[job.key] = LABELS.filter((l) => ls.includes(l));
          }
          saveLabels(labels, allKeys);
          break;
        } catch (err) {
          const message = (err as Error).message;
          if (/API_KEY_INVALID|PERMISSION_DENIED|UNAUTHENTICATED/.test(message)) throw err;
          if (/RESOURCE_EXHAUSTED|"code":\s*429/.test(message)) {
            if (/PerDay/i.test(message)) {
              throw new Error(`Gemini daily quota reached; labels so far are saved in ${LABELS_FILE}. Rerun tomorrow to continue.`);
            }
            const delay = retryDelaySeconds(message) ?? 60;
            if (tries <= 5) {
              console.warn(`    rate limited, waiting ${delay}s`);
              await sleep((delay + 1) * 1000);
              continue;
            }
          }
          console.warn(`    request failed: ${message.slice(0, 500)}`);
          break;
        }
      }
    }
    pending = pending.filter((j) => !labels[j.key]);
    if (pending.length && round < 3) console.log(`  ${pending.length} questions still unlabelled, retrying them`);
  }
  if (pending.length) console.warn(`  gave up on ${pending.length} questions: ${pending.map((j) => j.id).join(", ")}`);
  return labels;
}
